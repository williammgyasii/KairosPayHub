function normalizeCountryCode(countryCode?: string | null): string {
  const normalized = countryCode?.trim().toUpperCase() ?? ''
  if (normalized === 'USA') return 'US'
  return normalized
}

export function profileAddressPolicy(countryCode?: string | null): ProfileAddressPolicy {
  if (normalizeCountryCode(countryCode) === 'US') {
    return {
      showState: true,
      residenceLabel: 'Home address',
      residencePlaceholder: 'Street, city, or apartment',
      stateLabel: 'State',
      stateOptions: US_STATE_OPTIONS,
    }
  }

  return {
    showState: false,
    residenceLabel: 'Residence / location',
    residencePlaceholder: 'City, area, or address',
    stateLabel: 'State',
    stateOptions: [],
  }
}
